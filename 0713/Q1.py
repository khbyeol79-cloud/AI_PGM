# 학생들의 점수를 리스트로 저장
scores = [78, 85, 92, 68, 95, 88, 74]

# -------------------------------
# 1.1 평균 점수 계산
# -------------------------------

# 리스트의 모든 점수를 더한 후, 점수의 개수로 나누어 평균 계산
average = sum(scores) / len(scores)

# 평균 점수 출력
print("평균 점수 :", average)

# -------------------------------
# 1.2 최고점과 최저점 출력
# -------------------------------

# 리스트에서 가장 큰 값(최고점) 찾기
highest = max(scores)

# 리스트에서 가장 작은 값(최저점) 찾기
lowest = min(scores)

# 최고점 출력
print("최고점 :", highest)

# 최저점 출력
print("최저점 :", lowest)

# -------------------------------
# 1.3 80점 이상만 새로운 리스트 생성
# -------------------------------

# 리스트 컴프리헨션을 이용하여 80점 이상만 저장
high_scores = [score for score in scores if score >= 80]

# 새로운 리스트 출력
print("80점 이상 :", high_scores)

# -------------------------------
# 1.4 평균 이상인 학생 수 출력
# -------------------------------

# 평균 이상인 점수의 개수를 계산
count = sum(1 for score in scores if score >= average)

# 평균 이상인 학생 수 출력
print("평균 이상인 학생 수 :", count)